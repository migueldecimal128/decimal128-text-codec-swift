    @Test("hand-chosen parse vectors")
    func parseVectors() {
        for v in Self.vectors {
            let b = bidParse(v.str)
            if v.expectedHex == "invalid" {
                #expect(b.error != nil, "accepted <\(v.str)>")
                #expect(b.bits == canonicalQuietNaN, "<\(v.str)> left \(Hex.format32(b.bits))")
                continue
            }
            #expect(b.error == nil, "rejected <\(v.str)>: \(b.error ?? "")")
            #expect(b.bits == Hex.parseBracketed(v.expectedHex),
                    "<\(v.str)> gave \(Hex.format32(b.bits))")
        }
    }
