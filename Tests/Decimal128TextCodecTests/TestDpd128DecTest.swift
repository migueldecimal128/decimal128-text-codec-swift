    @Test("apply #hex -> text")
    func decode() {
        #expect(Self.decodeVectors.count == 206)
        for v in Self.decodeVectors {
            let bits = Hex.parse32(v.hex)!
            #expect(Decimal128TextCodec.dpd128ToString(bits) == v.text, "\(v.id)")
        }
    }

    @Test("apply text -> #hex")
    func encode() {
        #expect(Self.encodeVectors.count == 156)
        for v in Self.encodeVectors {
            let d = dpdParse(v.text)
            #expect(d.error == nil, "\(v.id): \(v.text)")
            #expect(Hex.format32(d.bits) == v.hex, "\(v.id): \(v.text)")
        }
    }

    /// Rendering then re-parsing normalises a non-canonical encoding.
    @Test("canonical #a -> #b")
    func canonical() {
        #expect(Self.canonicalVectors.count == 101)
        for v in Self.canonicalVectors {
            let text = Decimal128TextCodec.dpd128ToString(Hex.parse32(v.input)!)
            let d = dpdParse(text)
            #expect(d.error == nil, "\(v.id): \(text)")
            #expect(Hex.format32(d.bits) == v.canonical, "\(v.id): #\(v.input) -> \"\(text)\"")
        }
    }
